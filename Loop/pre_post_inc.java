class pre_post_inc{
public static void main(String[] args) {
    //POst increment
    int a=6;
    int b=a++;
    System.out.println("a : "+a);
    System.out.println("b : "+b);
 System.out.println();

    //pre increment
    int c=8;
    int d=++c;
    System.out.println("c : "+c);
    System.out.println("d : "+d);

}
} 
